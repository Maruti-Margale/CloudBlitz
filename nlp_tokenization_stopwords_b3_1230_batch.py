import re

def text_to_procedure(text):
    # Define basic actions and patterns (could be expanded)
    actions = {
        'add': r'\badd\b.*?(?=\.|,| and )',
        'stir': r'\bstir\b.*?(?=\.|,| and )',
        'concentrate': r'\b(evaporate|concentrate)\b.*?(?=\.|,| and )',
        'extract': r'\bextract\b.*?(?=\.|,| and )',
        'wash': r'\bwash\b.*?(?=\.|,| and )',
        'dry': r'\bdry\b.*?(?=\.|,| and )',
        'purify': r'\bpurif\w*\b.*?(?=\.|,| and )',
        'yield': r'\byield\b.*?(?=\.|,| and )'
    }

    text = text.lower()
    steps = []
    for action, pattern in actions.items():
        matches = re.findall(pattern, text)
        for match in matches:
            steps.append((action.upper(), match.strip('. ')))
    if not steps:
        # fallback: split by sentences as naive steps
        steps = [(f'STEP {i+1}', s.strip()) for i, s in enumerate(re.split(r'\.|\n', text)) if s.strip()]
    return steps

