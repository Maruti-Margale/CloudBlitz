import re

def extract_procedure(text):
    # Normalize spaces and lower the case for easier parsing
    text = text.replace('\n', ' ').strip()

    steps = []

    # Patterns for different actions
    add_pattern = re.compile(r'(?:was )?added(?: drop wise)?(?: at \d+°? ?C)?[^\.\,]*')
    stir_pattern = re.compile(r'stirred(?: for [^\.]+)?')
    concentrate_pattern = re.compile(r'(?:evaporated|concentrated) under vacuum')
    quench_pattern = re.compile(r'reaction was quenched with [^\.\,]+')
    extract_pattern = re.compile(r'extracted (?:with )?([^\.,]+)(?: \(\d+ ml\))?(?:,? \d+ x \d+ ml)?')
    wash_pattern = re.compile(r'washed with [^\.\,]+')
    dry_pattern = re.compile(r'dried over [^\.\,]+')
    purify_pattern = re.compile(r'purified by [^\.\,]+')
    yield_pattern = re.compile(r'afforded(?: an)? (.+) \(([\d\.]+ g), ([\d]+)% yield\)')

    # Extract ADD steps based on 'added' phrases
    add_matches = re.findall(add_pattern, text)
    for add in add_matches:
        add = add.strip()
        # Refine to include compound and quantity
        # Find preceding compound and quantity before 'added' phrase
        pre_add = re.findall(r'(\S.*?\)) ' + re.escape(add), text)
        if pre_add:
            compound = pre_add[0]
            steps.append(f"ADD {compound}")

    # STIR steps
    stir_matches = re.findall(stir_pattern, text)
    for stir in stir_matches:
        steps.append(f"STIR {stir[len('stirred'):].strip()}")

    # CONCENTRATE steps
    if re.search(concentrate_pattern, text):
        steps.append("CONCENTRATE")

    # QUENCH step
    quench_match = re.search(quench_pattern, text)
    if quench_match:
        quencher = quench_match.group(0).replace('reaction was quenched with ', '').strip()
        steps.append(f"QUENCH with {quencher}")

    # EXTRACT steps
    extract_matches = re.findall(r'extracted in ([^\(]+)(?: \((\d+ ml)\))?', text)
    if extract_matches:
        for ext_solvent, vol in extract_matches:
            vol_str = f"({vol})" if vol else ""
            steps.append(f"EXTRACT with {ext_solvent.strip()} {vol_str} 3 x")

    # WASH steps
    wash_match = re.search(wash_pattern, text)
    if wash_match:
        wash_what = wash_match.group(0).replace('washed with ', '').strip()
        steps.append(f"WASH with {wash_what}")

    # DRY step
    dry_match = re.search(dry_pattern, text)
    if dry_match:
        dry_what = dry_match.group(0).replace('dried over ', '').strip()
        steps.append(f"DRYSOLUTION over {dry_what}")

    # Concentrate again check
    if re.search(concentrate_pattern, text):
        steps.append("CONCENTRATE")

    # PURIFY steps
    purify_match = re.search(purify_pattern, text)
    if purify_match:
        steps.append("PURIFY")
        # Occasionally purification repeated twice
        if text.lower().count('purified by') > 1:
            steps.append("PURIFY")

    # YIELD
    yield_match = re.search(yield_pattern, text)
    if yield_match:
        compound_name = yield_match.group(1)
        compound_wt = yield_match.group(2)
        compound_yield = yield_match.group(3)
        steps.append(f"YIELD {compound_name} ({compound_wt} g, {compound_yield}% yield)")

    # Remove possible duplicates and preserve order
    seen = set()
    final_steps = []
    for step in steps:
        if step not in seen:
            final_steps.append(step)
            seen.add(step)

    return final_steps


